#!/usr/bin/env python3
"""
The micro-world: sentences with their frames, generated by a program (so every label is right, and there is
as much data as needed). The translator learns from these only.

All entities are made-up words (random syllables): a name, a place, a thing never repeats what the test has,
so the network cannot memorise who or what - it has to learn the structure "X went to the Y". In the network
every word that is not a function word is one of 64 anonymous buckets.

A template is a list of words; {A1} {A2} {A3} are entity slots, {A1:x} forces a form (p: one word without
"of", s: maybe with an adjective), {D:c} / {D:v} / {D:h} a direction word (compass / above, below / left,
right), {T} a time ("yesterday" or "this morning"), {PRON} he / she / they.
"""
import random
import re
import zlib

from engine import PREDICATES, ROLES

TEMPLATES = {
    "MOVE": ["{A1:p} VERB to the {A2:p} .", "{A1:p} and {A1:p} VERB to the {A2:p} .", "LINK {PRON} VERB to the {A2:p} .",
             "{T} {A1:p} VERB to the {A2:p} .", "{A1:p} VERB to the {A2:p} {T} .", "{A1:p} is in the {A2:p} .",
             "{A1:p} and {A1:p} are in the {A2:p} .", "{PRON} VERB to the {A2:p} .", "LINK {A1:p} VERB to the {A2:p} ."],
    "NOT_AT": ["{A1:p} is no longer in the {A2:p} .", "{A1:p} is not in the {A2:p} .", "{A1:p} is not in the {A2:p} anymore ."],
    "EITHER": ["{A1:p} is either in the {A2:p} or the {A3:p} .", "{A1:p} is in the {A2:p} or the {A3:p} ."],
    "GET": ["{A1:p} GETV the {A2} .", "{A1:p} GETV the {A2} there .", "{PRON} GETV the {A2} .", "LINK {PRON} GETV the {A2} there ."],
    "DROP": ["{A1:p} DROPV the {A2} .", "{A1:p} DROPV the {A2} there .", "{PRON} DROPV the {A2} ."],
    "GIVE": ["{A1:p} GIVEV the {A2} to {A3:p} .", "{PRON} GIVEV the {A2} to {A3:p} ."],
    "REL": ["the {A1:s} is {D:c} of the {A2:s} .", "the {A1:s} is {D:v} the {A2:s} .", "the {A1:s} is to the {D:h} of the {A2:s} ."],
    "ISA": ["{A1:p} is a {A2:p} .", "{A1:p} is an {A2:p} ."],
    "AFRAID": ["{A1:p} are afraid of {A2:p} .", "{A1:p} are scared of {A2:p} ."],
    "PROP": ["{A1:p} is {A2:p} ."],
    "FITS": ["the {A1} fits inside the {A2} .", "the {A1} fits in the {A2} ."],
    "BIGGER": ["the {A1} is bigger than the {A2} .", "the {A1} is larger than the {A2} ."],
    "Q_WHERE": ["where is {A1:p} ?", "where is the {A1} ?"],
    "Q_WHERE_BEFORE": ["where was {A1:p} before the {A2:p} ?", "where was the {A1} before the {A2:p} ?"],
    "Q_IS_AT": ["is {A1:p} in the {A2:p} ?"],
    "Q_COUNT": ["how many objects is {A1:p} carrying ?", "how many things is {A1:p} carrying ?", "how many objects does {A1:p} have ?"],
    "Q_LIST": ["what is {A1:p} carrying ?", "what does {A1:p} have ?"],
    "Q_GIVE_OBJ": ["what did {A1:p} give to {A3:p} ?"],
    "Q_GIVE_FROM": ["who gave the {A2} to {A3:p} ?", "who gave the {A2} ?"],
    "Q_GIVE_TO": ["who did {A1:p} give the {A2} to ?", "who received the {A2} ?"],
    "Q_REL_A1": ["what is {D:c} of the {A2:s} ?"],
    "Q_REL_A2": ["what is the {A1:s} {D:c} of ?"],
    "Q_REL_YN": ["is the {A1:s} {D:v} the {A2:s} ?", "is the {A1:s} to the {D:h} of the {A2:s} ?", "is the {A1:s} {D:c} of the {A2:s} ?"],
    "Q_PATH": ["how do you go from the {A1:p} to the {A2:p} ?", "how do i get from the {A1:p} to the {A2:p} ?"],
    "Q_AFRAID": ["what is {A1:p} afraid of ?", "what is {A1:p} scared of ?"],
    "Q_COLOR": ["what color is {A1:p} ?", "what colour is {A1:p} ?"],
    "Q_FITS": ["does the {A1} fit in the {A2} ?", "does the {A1} fit inside the {A2} ?"],
    "Q_BIGGER": ["is the {A1} bigger than the {A2} ?", "is the {A1} larger than the {A2} ?"],
    "Q_WHY": ["why did {A1:p} go to the {A2:p} ?", "why did {A1:p} get the {A2} ?"],
    "Q_WILL": ["where will {A1:p} go ?"],
}
WORDS = {
    "VERB": ["went", "journeyed", "travelled", "moved", "went back", "walked", "ran", "returned", "headed", "came back"],
    "GETV": ["got", "picked up", "grabbed", "took", "collected"],
    "DROPV": ["dropped", "put down", "discarded", "left", "threw away"],
    "GIVEV": ["gave", "handed", "passed"],
    "LINK": ["then", "after that", "afterwards", "following that", "next"],
}
DWORDS = {"c": ["north", "south", "east", "west"], "v": ["above", "below"], "h": ["left", "right"]}
TWORDS = [["yesterday"], ["this", "morning"], ["this", "afternoon"], ["this", "evening"]]
PRON = ["he", "she", "they"]
SLOT = re.compile(r"\{(A[123]|D|T|PRON)(?::(\w))?\}")
BUCKETS = 64


def _function_words():
    out = {".", "?", ","}
    for ts in TEMPLATES.values():
        for t in ts:
            out.update(w for w in t.split() if not w.startswith("{") and w not in WORDS)
    for ws in WORDS.values():
        out.update(w for x in ws for w in x.split())
    for ws in DWORDS.values():
        out.update(ws)
    out.update(w for t in TWORDS for w in t)
    out.update(PRON)
    out.update(["of", "it"])
    return sorted(out)


FUNCTION = _function_words()
VOCAB = {w: i + 1 for i, w in enumerate(FUNCTION)}                 # 0 = padding
N_VOCAB = len(VOCAB) + 1 + BUCKETS


def word_id(w):
    """a function word has its own id; any other word is one of the anonymous buckets"""
    return VOCAB[w] if w in VOCAB else len(VOCAB) + 1 + zlib.crc32(w.encode()) % BUCKETS


def tokens(text):
    return re.findall(r"[a-z']+|[.,?]", text.lower())


def made_up(rng):
    w = "".join(rng.choice("bcdfghjklmnprstvwz") + rng.choice("aeiou") for _ in range(rng.randint(2, 4)))
    w = w[:-1] if rng.random() < 0.3 else w
    return w if w not in VOCAB else made_up(rng)


def entity(rng, form):
    """the words of one entity"""
    r = rng.random()
    if form == "p" or r < 0.7:
        return [made_up(rng)]
    if form == "s" or r < 0.85:
        return [made_up(rng), made_up(rng)]                         # "red square"
    return [made_up(rng), "of", made_up(rng)]                       # "box of chocolates"


def sentence(rng, pred=None):
    """-> words, predicate, role of every word"""
    pred = pred or rng.choice(PREDICATES)
    words, roles = [], []
    for w in rng.choice(TEMPLATES[pred]).split():
        m = SLOT.fullmatch(w)
        if w in WORDS:
            for x in rng.choice(WORDS[w]).split():
                words.append(x)
                roles.append("O")
        elif not m:
            words.append(w)
            roles.append("O")
        elif m.group(1) == "D":
            words.append(rng.choice(DWORDS[m.group(2)]))
            roles.append("D")
        elif m.group(1) == "T":
            t = rng.choice(TWORDS)
            words += t
            roles += ["O"] * (len(t) - 1) + ["T"]
        elif m.group(1) == "PRON":
            words.append(rng.choice(PRON))
            roles.append("A1")
        else:
            e = entity(rng, m.group(2))
            words += e
            roles += [m.group(1)] * len(e)
    return words, pred, roles


def frame(words, pred, roles):
    """words with their roles -> the arguments of the frame: consecutive words of a role are one entity"""
    args, prev = {}, None
    for w, r in zip(words, roles):
        if r == "O":
            prev = None
            continue
        if r == prev and r.startswith("A"):
            args[r][-1] += " " + w
        else:
            args.setdefault(r, []).append(w)
        prev = r
    return pred, args


if __name__ == "__main__":
    rng = random.Random(1)
    print(len(FUNCTION), "function words;", N_VOCAB, "ids;", len(PREDICATES), "predicates;", ROLES)
    for _ in range(12):
        w, p, r = sentence(rng)
        print(" ".join(w), "->", frame(w, p, r))
